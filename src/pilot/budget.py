"""Compute budget for the reduced grid, from measured throughput (results/throughput_lact.csv).

    uv run python -m src.pilot.budget

Writes docs/compute_budget.md and results/tables/compute_budget.csv. This is arithmetic on measured
tokens per second and list prices; it contains no FLOP accounting and no claim about what the grid
will find.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"

# Modal list prices read from modal.com/pricing on 2026-11-18, in dollars per second
PRICE = {"A10": 0.000306, "H100": 0.001097, "H200": 0.001261}
CPU_CORE, MEMORY_GIB = 0.0000131, 0.00000222
CORES, MEMORY = 8, 32  # what each training container is given


def card(name: str) -> str:
    return next((k for k in ("H200", "H100", "A10") if k in name), name)


def hourly(card_name: str) -> float:
    return 3600 * (PRICE[card_name] + CORES * CPU_CORE + MEMORY * MEMORY_GIB)


def table() -> pd.DataFrame:
    frame = pd.read_csv(RESULTS / "throughput_lact.csv")
    frame = frame[frame["status"] == "ok"].copy()
    frame["card"] = frame["gpu"].map(card)
    frame["dollars_per_hour"] = frame["card"].map(hourly)
    frame["dollars_per_billion_tokens"] = 1e9 / frame["tokens_per_s"] / 3600 * frame["dollars_per_hour"]
    frame["gpu_hours_per_billion_tokens"] = 1e9 / frame["tokens_per_s"] / 3600
    return frame.sort_values(["size", "card", "batch", "chunk"])


def grid_cost(frame: pd.DataFrame, sizes=("160M", "410M"), chunks=(32, 128, 512, 1024)) -> pd.DataFrame:
    """Cost of one training run per (size, chunk) on the large card, per billion training tokens."""
    big = frame[frame["card"].isin(["H100", "H200"])]
    rows = []
    for size in sizes:
        for chunk in chunks:
            r = big[(big["size"] == size) & (big["chunk"] == chunk)]
            if r.empty:
                continue
            r = r.iloc[0]
            rows.append({"size": size, "chunk": chunk, "measured_on": r["gpu"], "tokens_per_s": r["tokens_per_s"],
                         "gpu_hours_per_billion_tokens": r["gpu_hours_per_billion_tokens"],
                         # priced as an H100 throughout, including the one row that landed on an H200
                         "dollars_per_billion_tokens": r["gpu_hours_per_billion_tokens"] * hourly("H100")})
    return pd.DataFrame(rows)


def document(frame: pd.DataFrame, grid: pd.DataFrame) -> str:
    def md(df, cols):
        head = "| " + " | ".join(cols.values()) + " |\n|" + "---|" * len(cols)
        return head + "\n" + "\n".join("| " + " | ".join(str(r[c]) for c in cols) + " |" for _, r in df.iterrows())

    view = frame.copy()
    view["tps"] = view["tokens_per_s"].map(lambda v: f"{v:,.0f}")
    view["mem"] = view["peak_memory_gb"].map(lambda v: f"{v:.0f} GB")
    view["cost"] = view["dollars_per_billion_tokens"].map(lambda v: f"${v:,.0f}")
    view["params_s"] = view["params"].map(lambda v: f"{v / 1e6:.0f}M")
    measured = md(view, {"size": "Size", "params_s": "Parameters", "gpu": "GPU", "batch": "Batch", "chunk": "Chunk",
                         "tps": "Tokens/s", "mem": "Peak memory", "cost": "Cost per billion tokens"})
    oom = pd.read_csv(RESULTS / "throughput_lact.csv")
    oom = oom[oom["status"] != "ok"]
    oom_note = ("Configurations that did not fit: " + "; ".join(
        f"{r['size']} chunk {r['chunk']} batch {r['batch']} on {r['gpu']}" for _, r in oom.iterrows()) + ".") if len(oom) else ""

    g = grid.copy()
    g["tps"] = g["tokens_per_s"].map(lambda v: f"{v:,.0f}")
    g["hours"] = g["gpu_hours_per_billion_tokens"].map(lambda v: f"{v:,.1f}")
    g["cost"] = g["dollars_per_billion_tokens"].map(lambda v: f"${v:,.0f}")
    per_run = md(g, {"size": "Size", "chunk": "Chunk", "tps": "Tokens/s", "hours": "GPU-hours per billion tokens",
                     "cost": "Cost per billion tokens"})

    per_seed_per_billion = g.groupby("size")["dollars_per_billion_tokens"].sum()
    hours_per_seed_per_billion = g.groupby("size")["gpu_hours_per_billion_tokens"].sum()
    both = per_seed_per_billion.sum()
    both_hours = hours_per_seed_per_billion.sum()
    scen = ["| Tokens per run | Seeds | Runs | GPU-hours | Cost | Same without chunk 32 |", "|---|---|---|---|---|---|"]
    no32 = g[g["chunk"] != 32]["dollars_per_billion_tokens"].sum()
    for tokens in (0.25, 1.0, 5.0):
        for seeds in (3, 5):
            scen.append(f"| {tokens:g} billion | {seeds} | {len(g) * seeds} | {both_hours * tokens * seeds:,.0f} | "
                        f"${both * tokens * seeds:,.0f} | ${no32 * tokens * seeds:,.0f} |")
    share32 = g[g["chunk"] == 32]["dollars_per_billion_tokens"].sum() / both
    return f"""# Compute budget for the reduced grid

Generated by `uv run python -m src.pilot.budget` from `results/throughput_lact.csv`. Arithmetic on measured
training throughput and list prices; no FLOP accounting.

## What was measured

Training throughput (forward, backward and optimiser step on random tokens) of the LaCT-style model used in
the pilots, at the roadmap's two scales, context 1024, bfloat16 autocast, the official LaCT op without
`torch.compile` and without its fused kernel (which does not compile on this Triton version).

{measured}

{oom_note}

Prices are Modal list prices read on 2026-11-18: A10 ${PRICE['A10'] * 3600:.2f}/h, H100 ${PRICE['H100'] * 3600:.2f}/h, plus {CORES} CPU
cores and {MEMORY} GiB of memory per container, which comes to ${hourly('A10'):.2f}/h and ${hourly('H100'):.2f}/h. One
H100 request was served by an H200; that row is priced as an H100 and its throughput is probably a little
higher than an H100 would give.

## Cost of one run, per billion training tokens, on an H100

{per_run}

Chunk 32 accounts for {share32:.0%} of the cost of a sweep over these four chunk lengths, because the op loops over
chunks in Python and each chunk is a fast-weight update. With `torch.compile` or a working fused kernel the
small-chunk cost would fall; these figures are for the code as it runs today.

## The reduced grid

The roadmap's reduced grid is: the architectures the pilot supports, two scales, five chunk lengths, three
seeds. Costed here: one architecture (LaCT-style), both scales, the four chunk lengths with measured
throughput. One seed of that sweep costs ${per_seed_per_billion.get('160M', float('nan')):,.0f} per billion tokens at 160M and
${per_seed_per_billion.get('410M', float('nan')):,.0f} at 410M. The roadmap does not fix the token budget per run, so it is a column:

{chr(10).join(scen)}

Not included: the fifth chunk length, the equal-wall-clock runs, the full-length precision study on the
scheduling class, the ablations, evaluation on long-context benchmarks, and reruns for failed jobs. The pilots
found that three seeds are too few to resolve small effects, which is why a five-seed column is shown.

## How to read it

- The grid is affordable or not depending almost entirely on the token budget per run and on whether chunk 32
  is in it.
- The 410M scale needs an 80 GB card: at chunk 32 and 128 it does not fit in 24 GB even at batch 4.
- A wall-clock comparison is where this layer's chunk length will matter most: throughput differs about
  {g[g['size'] == '160M']['tokens_per_s'].max() / g[g['size'] == '160M']['tokens_per_s'].min():.0f}-fold between chunk 32 and no test-time training at 160M, and about
  {g[g['size'] == '410M']['tokens_per_s'].max() / g[g['size'] == '410M']['tokens_per_s'].min():.0f}-fold at 410M.
"""


def main() -> int:
    frame = table()
    grid = grid_cost(frame)
    (RESULTS / "tables").mkdir(exist_ok=True)
    grid.to_csv(RESULTS / "tables" / "compute_budget.csv", index=False)
    (ROOT / "docs" / "compute_budget.md").write_text(document(frame, grid))
    print(grid.round(1).to_string(index=False))
    print(f"one seed, all four chunks, per billion tokens: ${grid['dollars_per_billion_tokens'].sum():,.0f} "
          f"({grid['gpu_hours_per_billion_tokens'].sum():,.0f} GPU-hours)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
