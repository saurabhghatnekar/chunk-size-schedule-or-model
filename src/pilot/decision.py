"""Assemble docs/go_no_go_decision.md from the pilots' summary tables and the budget.

    uv run python -m src.pilot.decision

Nothing is decided here: each verdict comes from a rule written down before its pilot ran, and the
combination rule is the table in docs/go_no_go_confirmatory.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / "results" / "tables"


def main() -> int:
    precision = pd.read_csv(TABLES / "pilot_precision_summary.csv").set_index("regime")
    first = pd.read_csv(TABLES / "pilot_architectural_summary.csv").iloc[0]
    confirm = pd.read_csv(TABLES / "pilot_confirmatory_summary.csv").set_index("rung")
    budget = pd.read_csv(TABLES / "compute_budget.csv")
    a, b = confirm.loc["A"], confirm.loc["B"]
    science = a["science"]
    per_billion = budget["dollars_per_billion_tokens"].sum()
    no32 = budget[budget["chunk"] != 32]["dollars_per_billion_tokens"].sum()
    hours = budget["gpu_hours_per_billion_tokens"].sum()

    effect_found = a["verdict"] == "EFFECT"
    condition_1 = ("**Met**, at small scale." if effect_found else "**Not met, by the rule as written.**")
    if science == "GO":
        bottom = ("**GO on the science.** Chunk length moves trained quality on the architectural class, on seeds that did "
                  "not suggest the hypothesis, and the direction holds at a model about eight times larger. The remaining "
                  "condition is the budget below, which is the author's call.")
    elif science == "WEAK GO":
        bottom = ("**WEAK GO.** The effect is confirmed at small scale but its direction at the larger size is not "
                  "established. Proceed to the roadmap-scale pilot before committing to the grid.")
    elif science.startswith("NO-GO"):
        bottom = (f"**NO-GO for the full paper, by the rule as written.** The confirmatory test needed t above {a['t_crit']} "
                  f"(one-sided 1%) and got {a['t']:.2f}. The registered test did not pass, which is not the same as showing "
                  "there is no effect. With the precision pilot detecting no chunk-length effect either, the roadmap's "
                  "fallback applies: the shorter paper built on the test, the classification, the kernel findings and "
                  "what the pilots did and did not detect.\n\n"
                  "**What the rule did not use, stated so the reader can weigh it.** The verdict above is not softened by "
                  f"this. In rung A the larger chunk was worse in {int(a['positive'])} of {int(a['seeds'])} new seeds, and in "
                  f"rung B in {int(b['positive'])} of {int(b['seeds'])} (rung B reuses seeds 5 to 7, so the two sets are not "
                  f"independent and are not pooled). The run-to-run floor is {a['floor']:.4f} nats; the "
                  f"smallest rung A difference is {a['d_min']:.4f} ({a['d_min'] / a['floor']:.1f} floors) and the mean is "
                  f"{a['d_mean']:.4f} ({a['d_mean'] / a['floor']:.0f} floors). The test failed at the 1% level because one seed's "
                  "difference, in the predicted direction, was several times the others and inflated the variance. A "
                  "paired t-test at 1% with six seeds was a fragile choice of statistic; that was a design error made "
                  "before the data, and it is the rule that was registered. A reader who weighs these facts may reasonably "
                  "conclude the effect is real at this scale. The rule does not license saying so as a result.")
    else:
        bottom = "**UNDECIDED.** The confirmatory pilot did not complete."

    text = f"""# Go or no-go: the decision

Generated by `uv run python -m src.pilot.decision` from the summary tables in `results/tables/`. Each verdict
below comes from a rule written down before the corresponding runs existed; the files holding those rules are
linked, and their hashes are stored in the result rows.

## The roadmap's condition

Go if a pilot shows a chunk effect above noise on the architectural class, **or** a precision effect above
noise on the scheduling class, **and** the compute budget covers a reduced grid.

## 1. A chunk effect above noise on the architectural class: {condition_1}

| Pilot | Rule | Outcome |
|---|---|---|
| First pilot, seeds 0-4, runs treated as independent | [go_no_go_architectural.md](go_no_go_architectural.md) | {first['verdict']} (F = {first['F']:.2f} against {first['F_crit']}; within-cell spread {first['s_within']:.4f}) |
| Confirmatory, rung A: six new seeds, paired by seed, 5.2M parameters | [go_no_go_confirmatory.md](go_no_go_confirmatory.md) | **{a['verdict']}** (chunk 512 minus chunk 32: mean {a['d_mean']:+.4f} nats, t = {a['t']:.2f}, run-to-run floor {a['floor']:.4f}) |
| Confirmatory, rung B: three seeds, about 39M parameters | same file | **{b['verdict']}** (per seed: {b['d_per_seed']}) |

Write-ups: [pilot_architectural.md](pilot_architectural.md), [pilot_confirmatory.md](pilot_confirmatory.md).

## 2. A precision effect above noise on the scheduling class: **Not met.**

No chunk-length effect on final loss was detected at this scale.

| Arithmetic | Outcome | Largest same-seed change, chunk 64 against 16 | Seed spread |
|---|---|---|---|
| bfloat16 | {precision.loc['bf16', 'verdict']} | {precision.loc['bf16', 'd_max_abs']:.4f} | {precision.loc['bf16', 'sigma_seed']:.4f} |
| float32, TF32 | {precision.loc['fp32_tf32', 'verdict']} | {precision.loc['fp32_tf32', 'd_max_abs']:.4f} | {precision.loc['fp32_tf32', 'sigma_seed']:.4f} |
| float32, IEEE | {precision.loc['fp32_ieee', 'verdict']} | {precision.loc['fp32_ieee', 'd_max_abs']:.4f} | {precision.loc['fp32_ieee', 'sigma_seed']:.4f} |

Rule: [go_no_go.md](go_no_go.md). Write-up: [pilot_precision.md](pilot_precision.md).

## 3. The compute budget covers a reduced grid: for the author to decide

One seed of a four-chunk sweep at both planned sizes costs about **${per_billion:,.0f} per billion training tokens**
on an H100 ({hours:,.0f} GPU-hours), or ${no32:,.0f} without chunk 32. Three seeds at one billion tokens per run is
about ${3 * per_billion:,.0f}; five seeds is about ${5 * per_billion:,.0f}. This excludes the equal-wall-clock runs, the
precision study, the ablations and reruns. Details: [compute_budget.md](compute_budget.md).

## Decision on the science

{bottom}

## What the decision rests on, and what it does not

- Every pilot is small: 5M to 39M parameters, minutes of training, one dataset, a 1024-byte context. The
  roadmap's pilot scale is 160M parameters. A go here means the effect exists at a size that was affordable to
  test, which is what the roadmap asks of the pilot; it is not evidence about scale.
- The architectural effect is measured at equal training steps. Smaller chunks cost several times more compute
  per token, so the equal-wall-clock answer may differ. That is the study's central measurement, not something
  the pilot settles.
- One architectural layer type (LaCT-style) was piloted. FLASH and HLA were classified but not trained.
- The first architectural pilot's rule failed to detect what the confirmatory pilot tested. Both outcomes are
  reported; the second one was run on new seeds with its test fixed in advance precisely because the first
  reading was post hoc.
"""
    (ROOT / "docs" / "go_no_go_decision.md").write_text(text)
    print(f"science: {science} | rung A {a['verdict']} | rung B {b['verdict']}")
    print("wrote docs/go_no_go_decision.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
